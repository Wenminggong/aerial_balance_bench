def _controller_table(subsets: dict[str, Any]) -> str:
    rows = [
        "| 数据子集 | 对齐时间 | nominal 总加速度 RMSE | v1.0 RMSE | 因果 RMSE | 因果 vs v1.0 MSE |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for name, label in (("completed", "完整轨迹"), ("stress", "异常结束"), ("all", "全部")):
        if name not in subsets:
            continue
        values = subsets[name]
        total = values["total_acceleration"]
        rows.append(
            f"| {label} | {values['horizon_s']:.4f} s | {total['nominal']['rmse']:.5f} | "
            f"{total['v1_deployed']['rmse']:.5f} | {total['causal_lmax_0p04']['rmse']:.5f} | "
            f"{_pct(total['causal_vs_v1_mse_improvement_fraction'])} |"
        )
    return "\n".join(rows)


def _timing_table(values: dict[str, Any]) -> str:
    rows = [
        "| 偏移步数 | 时间 | nominal RMSE | v1.0 RMSE | 因果 RMSE |",
        "|---:|---:|---:|---:|---:|",
    ]
    for shift in range(7):
        item = values[f"shift_{shift}"]
        rows.append(
            f"| {shift} | {item['horizon_s']:.4f} s | {item['nominal']['rmse']:.5f} | "
            f"{item['v1_deployed']['rmse']:.5f} | {item['causal_lmax_0p04']['rmse']:.5f} |"
        )
    return "\n".join(rows)


def _rollout_table(values: dict[str, Any]) -> str:
    rows = [
        "| 步数 | 时间 | v1 pb RMSE | 因果 pb RMSE | pb MSE 改变量 | v1 vb RMSE | 因果 vb RMSE | vb MSE 改变量 |",
        "|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for horizon, item in values.items():
        improvement = item["causal_vs_v1_mse_improvement_fraction"]
        rows.append(
            f"| {horizon[1:]} | {item['horizon_s']:.4f} s | "
            f"{item['v1_deployed']['causal_pb_rmse']:.5f} | "
            f"{item['causal_lmax_0p04']['causal_pb_rmse']:.5f} | {_pct(improvement['causal_pb'])} | "
            f"{item['v1_deployed']['causal_vb_rmse']:.5f} | "
            f"{item['causal_lmax_0p04']['causal_vb_rmse']:.5f} | {_pct(improvement['causal_vb'])} |"
        )
    return "\n".join(rows)


def _rollout_group_table(groups: dict[str, Any]) -> str:
    rows = [
        "| 轨迹组 | pb MSE 改变量 | vb MSE 改变量 |",
        "|---|---:|---:|",
    ]
    for group, horizons in groups.items():
        values = horizons["h33"]["causal_vs_v1_mse_improvement_fraction"]
        rows.append(
            f"| {group} | {_pct(values['causal_pb'])} | {_pct(values['causal_vb'])} |"
        )
    return "\n".join(rows)


def _bootstrap_sentence(label: str, values: dict[str, Any]) -> str:
    return (
        f"{label}：{_pct(values['estimate'])}，trial-cluster 95% CI "
        f"[{_pct(values['ci95_low'])}, {_pct(values['ci95_high'])}]，"
        f"bootstrap 改善概率 {100.0 * values['bootstrap_probability_improvement']:.1f}%。"
    )


def _bootstrap_pair_table(values: dict[str, Any]) -> str:
    rows = [
        "| 状态 | MSE 改变量 | 95% CI | bootstrap 改善概率 |",
        "|---|---:|---:|---:|",
    ]
    for state, label in (("causal_pb", "pb"), ("causal_vb", "vb")):
        item = values[state]
        rows.append(
            f"| {label} | {_pct(item['estimate'])} | "
            f"[{_pct(item['ci95_low'])}, {_pct(item['ci95_high'])}] | "
            f"{100.0 * item['bootstrap_probability_improvement']:.1f}% |"
        )
    return "\n".join(rows)


def _diagnostic_table(values: dict[str, Any]) -> str:
    bounds = values["causal_training_bounds"]
    models = values["models"]
    rows = [
        f"完整轨迹实际状态的任一特征超出因果训练 min/max 比例：{100.0 * bounds['any_feature_ood_fraction']:.2f}% 。",
        "",
        "| 模型 | 输出绝对值 P95 | 饱和率 | 缩放 Jacobian P95/P99/max | 相邻输出变化 P95/P99/max |",
        "|---|---:|---:|---:|---:|",
    ]
    for name in ("v1_deployed", "causal_lmax_0p04"):
        item = models[name]
        rows.append(
            f"| {MODEL_LABELS[name]} | {item['residual_abs_p95_mps2']:.5f} | "
            f"{100.0 * item['saturation_fraction']:.3f}% | "
            f"{item['scaled_state_jacobian_norm_p95_mps2']:.5f} / "
            f"{item['scaled_state_jacobian_norm_p99_mps2']:.5f} / "
            f"{item['scaled_state_jacobian_norm_max_mps2']:.5f} | "
            f"{item['adjacent_residual_change_p95_mps2']:.5f} / "
            f"{item['adjacent_residual_change_p99_mps2']:.5f} / "
            f"{item['adjacent_residual_change_max_mps2']:.5f} |"
        )
    return "\n".join(rows)


def _pct(value: float) -> str:
    return f"{100.0 * value:+.1f}%"


def _read_json(path: Path) -> dict[str, Any]:
    with path.open("r", encoding="utf-8") as stream:
        value = json.load(stream)
    if not isinstance(value, dict):
        raise ValueError(f"Expected JSON object in {path}")
    return value


def _write_json(path: Path, value: Any) -> None:
    with path.open("w", encoding="utf-8") as stream:
        json.dump(value, stream, indent=2, sort_keys=True, ensure_ascii=False, allow_nan=False)
        stream.write("\n")


def _display_path(path: Path) -> str:
    try:
        return path.resolve().relative_to(REPO_ROOT).as_posix()
    except ValueError:
        return str(path.resolve())


